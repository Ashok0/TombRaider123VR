"""Verify global laracoll binding in every supported TR1-3 DLL fixture.

python tools/verify_roomscale_collision.py [--generate]
--generate refreshes the native instruction fixtures used by the C++ tests.
"""
from pathlib import Path
import re
import subprocess
import sys

import capstone
from capstone.x86 import X86_OP_MEM, X86_OP_REG, X86_REG_RIP, X86_REG_EAX
import pefile
from port_build import DLL_LAYOUT

root = Path(__file__).resolve().parents[1]
source = (root / 'src/GameDll.cpp').read_text(encoding='utf-8')
layouts = {}
for match in re.finditer(r'\{\s*L"(tomb[123]\.dll)",\s*"[^"]*",\s*(0x[0-9A-Fa-f]+),(.*?)\}', source, re.S):
    values = [int(v, 0) for v in re.findall(r'0x[0-9A-Fa-f]+|\b\d+\b',
              re.sub(r'/\*.*?\*/', '', match[3], flags=re.S))]
    columns = [name for name in DLL_LAYOUT if name != 'S_InitialisePolyList']
    assert len(values) == len(columns)
    layouts[match[1], int(match[2], 16)] = dict(zip(columns, values))

decoder = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
decoder.detail = True
fixtures = {}
checks = 0
for directory in ['PDB', 'build/current-retail-verify', 'build/current-gold-verify',
                  'build/current-october-verify', 'build/current-egs-verify']:
    for game in (1, 2, 3):
        name = f'tomb{game}.dll'
        path = root / directory / name
        pe = pefile.PE(str(path))
        data = pe.get_memory_mapped_image()
        stamp = pe.FILE_HEADER.TimeDateStamp
        entry = layouts[name, stamp]['LaraAboveWater']
        code = data[entry:entry + 64]
        # Independently decode the stores, rather than assume byte offsets.
        stores = [i for i in decoder.disasm(code, entry)
                  if i.mnemonic == 'mov' and len(i.operands) == 2
                  and i.operands[0].type == X86_OP_MEM
                  and i.operands[0].mem.base == X86_REG_RIP
                  and i.operands[0].size == 4
                  and i.operands[1].type == X86_OP_REG
                  and i.operands[1].reg == X86_REG_EAX]
        assert len(stores) == 3, (path, 'three initial coordinate stores')
        targets = [i.address + i.size + i.operands[0].mem.disp for i in stores]
        assert targets == [targets[0], targets[0] + 4, targets[0] + 8]
        collision = targets[0] - 100  # PDB coll_info.old offset
        section = pe.get_section_by_rva(collision)
        assert section and section.Characteristics & 0x80000000, (path, 'writable global')
        assert collision + 144 <= section.VirtualAddress + section.Misc_VirtualSize
        if directory == 'PDB':
            symbols = subprocess.check_output([sys.executable, str(root / 'tools/pdbdump.py'),
                                               str(path)], text=True)
            symbol = re.search(r'^(0x[0-9A-Fa-f]+)\s+data\s+144\s+laracoll\s*$', symbols, re.M)
            assert symbol and int(symbol[1], 16) == collision, (path, 'PDB laracoll identity')
        fixture = (game, collision - entry, code)
        if stamp in fixtures:
            assert fixtures[stamp] == fixture
        fixtures[stamp] = fixture
        checks += 1
        print(f'{directory}/{name}: verified laracoll RVA 0x{collision:08X}')

text = '// Generated by tools/verify_roomscale_collision.py from supported native DLLs.\n'
text += 'struct NativeCollisionFixture { int game; intptr_t delta; uint8_t code[64]; };\n'
text += 'constexpr NativeCollisionFixture kNativeCollisionFixtures[]={\n'
for stamp, (game, delta, code) in fixtures.items():
    text += f'    // PE timestamp 0x{stamp:08X}\n    {{{game},0x{delta:X},{{\n'
    for at in range(0, 64, 16):
        text += '        ' + ','.join(f'0x{byte:02X}' for byte in code[at:at + 16]) + ',\n'
    text += '    }},\n'
text += '};\n'
target = root / 'tests/roomscale_collision_fixtures.h'
if '--generate' in sys.argv:
    target.write_text(text, encoding='utf-8')
else:
    assert target.read_text(encoding='utf-8') == text, 'native collision fixture mismatch'
print(f'PASS: {checks} binary fixtures, {len(fixtures)} unique DLL builds')
